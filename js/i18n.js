export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.th[key] ?? key;
  if (typeof s === 'function') return s(vars);
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

// ข้อความในหน้า HTML: data-i18n="key" (ข้อความ) · data-i18n-attr="attr:key;attr:key" · data-wd="0-6" (ชื่อวันย่อ)
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(key));
    }
  });
  root.querySelectorAll('[data-wd]').forEach((el) => {
    el.textContent = t('wd')[el.dataset.wd];
  });
}
